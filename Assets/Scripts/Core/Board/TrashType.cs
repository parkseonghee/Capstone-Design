namespace RecycleLife.Core
{
    /// <summary>
    /// 보드에 나오는 블록의 종류. <b>연쇄 판정의 단위</b>다
    /// (CORE_COMBAT.md §8-1 확정: 같은 종류끼리 묶인다).
    ///
    /// 각 종류가 적인지 아이템인지 벽인지는 여기가 아니라 TrashStatsConfig 에셋이 정한다 —
    /// 값이 역할을 정하므로 이 enum은 "구분표"일 뿐이다(TrashStats 주석 참조).
    ///
    /// 이름은 기획서에서도 "임시명"이라 확정 시 바뀔 수 있는데,
    /// enum 멤버 이름만 바꾸면 되고 저장된 값은 정수라 그대로 유지된다.
    ///
    /// <b>순서를 바꾸거나 중간에 끼워 넣지 말 것.</b> 에셋에 정수로 직렬화돼 있어서
    /// 기존 값의 번호가 밀리면 저장된 데이터가 다른 종류로 뒤바뀐다. 추가는 항상 맨 뒤에.
    /// 번호는 빈틈 없이 이어져야 한다 — 스폰 추첨이 0..N-1로 훑는다(TrashTypePicker).
    /// </summary>
    public enum TrashType
    {
        // ── 잡몹 (기믹 없는 3종) ─────────────────────────────────────────
        /// <summary>종잇조각 (잡몹 1). 체력 1 / 공격력 1. 스테이지: 강. 연쇄 학습용 기본 적.</summary>
        Paper = 0,

        /// <summary>페트병 (잡몹 2). 체력 2 / 공격력 1. 스테이지: 강.</summary>
        Plastic = 1,

        /// <summary>유리조각 (잡몹 5). 체력 3 / 공격력 2. 스테이지: 산. 딜은 세지만 단단하다.</summary>
        Glass = 2,

        // ── 아이템 ───────────────────────────────────────────────────────
        /// <summary>체력 포션. 부딪히면 먹고, 같은 포션끼리 연쇄된다.</summary>
        Potion = 3,

        // ── 벽 (장애물 3종) ──────────────────────────────────────────────
        // 공격력이 없어 피해를 주지 않는 대신 시간과 동선을 빼앗는다.
        // 밸런싱 v1 §3: "때릴 수는 있지만 때리면 손해"인 판단을 만드는 것이 목적이다.
        /// <summary>나무 더미 (벽 1). 체력 3. 파괴 가능.</summary>
        Wood = 4,

        /// <summary>콘크리트 (벽 2). 체력 5. 파괴는 되지만 오래 걸려 우회를 유도한다.</summary>
        Concrete = 5,

        /// <summary>철제 구조물 (벽 3). 체력 6. 파괴가 비효율적이라 사실상 지형이다.</summary>
        Steel = 6,

        // ── 잡몹 (나중에 추가된 6종) ─────────────────────────────────────
        // 위쪽 잡몹 3종과 떨어져 있는 건 순서를 바꿀 수 없기 때문이다(위 주석 참조).
        // 밸런싱 v1 §2의 No 순서가 아니라 추가된 순서로 붙는다.
        //
        // 기믹은 아직 전부 미구현이다. 지금은 체력·공격력만 있는 평범한 적으로 나온다.
        // 스턴형(3·7번)과 미정 기믹(4·6·8·9번)은 상태이상 시스템이 생긴 뒤에 붙인다.

        /// <summary>찌그러진 캔 (잡몹 3). 체력 2 / 공격력 1. 스테이지: 강. <b>스턴형 — 기믹 미구현.</b></summary>
        Can = 7,

        /// <summary>비닐봉지 (잡몹 4). 체력 2 / 공격력 1. 스테이지: 산. 기믹 미정.</summary>
        Vinyl = 8,

        /// <summary>스티로폼 (잡몹 6). 체력 3 / 공격력 1. 스테이지: 산. 기믹 미정.</summary>
        Styrofoam = 9,

        /// <summary>폐타이어 (잡몹 7). 체력 3 / 공격력 2. 스테이지: 바다. <b>스턴형 — 기믹 미구현.</b></summary>
        Tire = 10,

        /// <summary>폐어망 (잡몹 8). 체력 4 / 공격력 1. 스테이지: 바다. 기믹 미정(이동 방해 예상).</summary>
        Net = 11,

        /// <summary>오염 폐기물 (잡몹 9). 체력 4 / 공격력 2. 스테이지: 바다. 기믹 미정(연쇄 불가 예상).</summary>
        Sludge = 12,
    }
}
